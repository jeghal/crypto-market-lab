const SYMBOL_PROGRESS_STEPS = 5;
let baseProgressSteps = 0;
let symbolProgressSteps = {};
let totalProgressSteps = 0;

function resetProgressTracking(symbols) {
  baseProgressSteps = 0;
  symbolProgressSteps = Object.fromEntries(symbols.map((symbol) => [symbol, 0]));
}

function refreshProgress() {
  const symbolStepsDone = Object.values(symbolProgressSteps)
    .reduce((sum, steps) => sum + steps, 0);
  if (totalProgressSteps > 0) {
    progressWrap.style.display = "block";
  }
  updateProgress(baseProgressSteps + symbolStepsDone, totalProgressSteps);
}

function advanceBaseProgress(steps = 1) {
  baseProgressSteps += steps;
  refreshProgress();
}

function setSymbolProgress(symbol, steps) {
  const nextSteps = Math.max(0, Math.min(SYMBOL_PROGRESS_STEPS, steps));
  symbolProgressSteps[symbol] = nextSteps;
  refreshProgress();
}

function advanceSymbolProgress(symbol, steps = 1) {
  setSymbolProgress(symbol, (symbolProgressSteps[symbol] || 0) + steps);
}

function completeSymbolProgress(symbol) {
  setSymbolProgress(symbol, SYMBOL_PROGRESS_STEPS);
}

function buildBundleSummary({
  symbols,
  startedAt,
  finishedAt,
  finalMarketSnapshotCapturedAt,
  symbolResults,
  symbolArtifacts
}) {
  const successCount = symbolResults.filter((item) => item.status === "success").length;
  const errorCount = symbolResults.filter((item) => item.status === "error").length;

  const perSymbol = symbols.map((symbol) => {
    const artifact = symbolArtifacts[symbol] || {};
    const metadata = artifact.metadata || {};
    const summary = metadata.summary || {};
    const derived = metadata.derived_metrics_overview || {};
    const execution = metadata.execution_check || {};
    const finalSnapshot = metadata.final_market_snapshot || {};
    const symbolResult = symbolResults.find((item) => item.symbol === symbol) || {};

    return {
      symbol,
      status: symbolResult.status || "unknown",
      files_count: Array.isArray(artifact.filesCreated) ? artifact.filesCreated.length : 0,
      latest_price: summary.latest_price ?? null,
      trend_bias: {
        d1: derived.bias_1d ?? "unknown",
        h4: derived.bias_4h ?? "unknown",
        h1: derived.bias_1h ?? "unknown",
        m15: derived.bias_15m ?? "unknown"
      },
      execution_window_status: derived.execution_window_status ?? "unknown",
      execution_check_status: execution.status ?? "unknown",
      rounded_quantity: execution.rounded_quantity ?? null,
      estimated_notional: execution.estimated_notional ?? null,
      final_snapshot_captured_at: finalSnapshot.captured_at ?? null,
      final_snapshot_staleness_ms: {
        book_ticker: finalSnapshot.book_ticker_staleness_ms ?? null,
        ticker_24h: finalSnapshot.ticker_24h_staleness_ms ?? null
      }
    };
  });

  return {
    bundle_type: "market_bundle_summary",
    generated_at: finishedAt,
    collection_started_at: startedAt,
    collection_finished_at: finishedAt,
    final_market_snapshot_captured_at: finalMarketSnapshotCapturedAt,
    symbols,
    totals: {
      symbols_total: symbols.length,
      symbols_success: successCount,
      symbols_error: errorCount
    },
    per_symbol: perSymbol
  };
}

